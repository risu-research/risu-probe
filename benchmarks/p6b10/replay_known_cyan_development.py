"""B9 source-real CYAN760/785 development replay for B10 fidelity checker.

These two known defects were used to design RMC507/RMC508 and are NEVER
counted as new independent validation. All result bodies originate in B9's
pinned upstream TypeScript component execution, not generated by this adapter.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path

def read(path:Path,family:str):
    x=json.loads(path.read_text())
    if (x.get('schema')!='risu-p6b9-cyan-authentic-framework-v1'
            or x.get('family')!=family or
            x.get('component_origin')!='ACTUAL_UPSTREAM_SOURCE_UNIT_EXECUTION_NOT_WIRE'):
        raise ValueError('Not a genuine B9 source component result')
    if not all(type(x.get(key)) is dict for key in ('issue','control')):
        raise ValueError('No verified issue + normal controls')
    return x

def prepared(x):
    family=x['family']
    error=family=='CYAN760'
    source='/error/message' if error else '/effectiveQuery'
    prefix='Error: ' if error else '**effectiveQuery:** '
    mode='markdown-rendered' if error else 'raw-copy'
    rows=[{'jsonrpc':'2.0','id':1,'method':'tools/list','params':{}},
          {'jsonrpc':'2.0','id':1,'result':{'tools':[{
              'name':family+'_'+name,
              'inputSchema':{'type':'object'},
              'outputSchema':{'type':'object'}
              } for name in ('issue','control')]}}]
    rules=[]
    for id,name in enumerate(('issue','control'),2):
        res=x[name]
        content=res.get('content')
        if type(content) is not list or not content or len(content)>16:
            raise ValueError('Genuine source content missing')
        selected=next((i for i,item in reversed(list(enumerate(content)))
                      if type(item) is dict and item.get('type')=='text' and
                         type(item.get('text')) is str and prefix in item['text']),None)
        if selected is None:raise ValueError('No authentic labelled source text')
        rules.append({'id':family+'_'+name,'tool':family+'_'+name,
                      'source':source,'content_index':selected,
                      'prefix_raw':prefix,'mode':mode,'on_error':error})
        rows.extend([
            {'jsonrpc':'2.0','id':id,'method':'tools/call',
             'params':{'name':family+'_'+name,'arguments':{}}},
            {'jsonrpc':'2.0','id':id,'result':res},
        ])
    return rows,{'schema':'risu-mcp-display-contract-v1','rules':rules}

def score(family,old,fixed,old_report,fixed_report):
    want='RMC507' if family=='CYAN760' else 'RMC508'
    o=[f['rule_id'] for f in old_report.get('findings',[])]
    f=[x['rule_id'] for x in fixed_report.get('findings',[])]
    ok=(o==[want] and not f and
        old_report['summary']['explicit_display_rules_checked']==2 and
        fixed_report['summary']['explicit_display_rules_checked']==2 and
        old_report['summary']['explicit_display_rules_passed']==1 and
        fixed_report['summary']['explicit_display_rules_passed']==2)
    return {'schema':'risu-p6b10-known-development-source-replay-v1',
            'family':family,'role':'DEVELOPMENT_INPUT_NO_INDEPENDENT_HOLDOUT_CREDIT',
            'actual_source_component_reused':True,
            'known_bug_before_findings':o,'official_fix_findings':f,
            'normal_control_passed':bool(ok),
            'b10_regression_passed':bool(ok),
            'reconstructed_jsonrpc':True}

def main():
    p=argparse.ArgumentParser()
    p.add_argument('mode',choices=('prepare','score'))
    p.add_argument('family',choices=('CYAN760','CYAN785'))
    p.add_argument('paths',nargs='+',type=Path)
    a=p.parse_args()
    if a.mode=='prepare':
        if len(a.paths)!=3:raise SystemExit(2)
        x=read(a.paths[0],a.family)
        rows,rules=prepared(x)
        a.paths[1].write_text(''.join(json.dumps(v,sort_keys=True)+'\n' for v in rows))
        a.paths[2].write_text(json.dumps(rules,indent=2)+'\n')
    else:
        if len(a.paths)!=5:raise SystemExit(2)
        o,f,ro,rf,out=a.paths
        x=score(a.family,read(o,a.family),read(f,a.family),
                json.loads(ro.read_text()),json.loads(rf.read_text()))
        out.write_text(json.dumps(x,indent=2,sort_keys=True)+'\n')
        print(json.dumps(x,indent=2,sort_keys=True))
        if not x['b10_regression_passed']:raise SystemExit(1)

if __name__=='__main__':main()
